#!/usr/bin/env python3
"""Generate the keyword search entries for the magic cast window.

Run from the mod folder:  python3 tools/generate_spell_search_keywords.py
Re-run it whenever a spell is added or renamed.

For every spell name (zz_valyria_magic_<school>_magic.<NNN>.name) it takes each word
(skipping filler such as "Mystery" and "of") and writes every prefix of 3 or more letters,
in lowercase and capitalised, as <spell flag>.zkw01 ... .zkwNN. Every spell gets the same
number of slots; unused ones are empty so they never match. The cast window compares the
searched word against these with EqualTo_string (gui/custom_gui/zz_valyria_magic_casting.gui).
"""
import glob, os, re, struct, sys

SLOTS = 48     # must match the number of comparisons in magic_list_item's visible expression
SUFFIX = '.zkw'  # must match the suffix in that expression; chosen because no key it makes clashes with a game or mod key
GAME_LOC = '/home/mcliff/steam_games/common/Crusader Kings III Beta/game/localization/english'
MOD_DIR = '..'  # other mods in the playset, checked for clashes too
STOP = {'mystery', 'of', 'the', 'a', 'an', 'and', 'to', 'in', 'on', 'for', 'from', 'with', 'by', 'at', 'into'}
OUT = 'localization/english/magic/zz_valyria_magic_search_keywords_l_english.yml'

def murmur3(text, seed=0):
    """The hash the game uses for localisation keys (MurmurHash3, 32-bit). Two keys with the same hash clash."""
    d = text.encode('utf-8'); h = seed; c1, c2 = 0xcc9e2d51, 0x1b873593; n = len(d)
    for i in range(0, n // 4 * 4, 4):
        k = struct.unpack('<I', d[i:i + 4])[0]
        k = (k * c1) & 0xffffffff; k = ((k << 15) | (k >> 17)) & 0xffffffff; k = (k * c2) & 0xffffffff
        h ^= k; h = ((h << 13) | (h >> 19)) & 0xffffffff; h = (h * 5 + 0xe6546b64) & 0xffffffff
    t = d[n // 4 * 4:]; k = 0
    for i, b in enumerate(t):
        k |= b << (8 * i)
    if t:
        k = (k * c1) & 0xffffffff; k = ((k << 15) | (k >> 17)) & 0xffffffff; k = (k * c2) & 0xffffffff; h ^= k
    h ^= n; h ^= h >> 16; h = (h * 0x85ebca6b) & 0xffffffff; h ^= h >> 13; h = (h * 0xc2b2ae35) & 0xffffffff; h ^= h >> 16
    return h

def prefixes(name):
    text = re.sub(r'\[[^\]]*\]|\$[^$]*\$', '', name)
    words = [w.replace("'", '') for w in re.findall(r"[A-Za-z']+", text)]
    words = [w for w in words if w.lower() not in STOP and len(w) >= 3]
    out = []
    for w in words:
        for i in range(3, len(w) + 1):
            p = w[:i].lower()
            for v in (p, p[0].upper() + p[1:]):
                if v not in out:
                    out.append(v)
    return out

names = {}
for f in glob.glob('localization/english/**/*.yml', recursive=True):
    for line in open(f, encoding='utf-8-sig', errors='replace'):
        m = re.match(r'\s+zz_valyria_magic_([a-z]+)_magic\.(\d{3})\.name:\d*\s*"(.*)"', line)
        if m:
            names[f'zz_valyria_magic_{m.group(1)}_magic_{m.group(2)}'] = m.group(3)

lines = ['l_english:',
         ' # Generated by tools/generate_spell_search_keywords.py. Do not edit by hand.']
too_long = []
for key in sorted(names):
    kws = prefixes(names[key])
    if len(kws) > SLOTS:
        too_long.append((key, len(kws)))
        kws = kws[:SLOTS]
    kws += [''] * (SLOTS - len(kws))
    for i, kw in enumerate(kws, 1):
        lines.append(f'  {key}{SUFFIX}{i:02d}:0 "{kw}"')
# Check the generated keys against every key the game and the other mods define
known = {}
roots = [GAME_LOC] + [os.path.join(MOD_DIR, d, 'localization') for d in os.listdir(MOD_DIR)
                      if os.path.isdir(os.path.join(MOD_DIR, d)) and not d.endswith('_agot')]
for root in roots:
    for f in glob.glob(root + '/**/*.yml', recursive=True):
        if f.endswith(os.path.basename(OUT)):
            continue
        for line in open(f, encoding='utf-8-sig', errors='replace'):
            m = re.match(r'\s*([A-Za-z0-9_.\-]+):\d*\s*"', line)
            if m:
                known.setdefault(murmur3(m.group(1)), m.group(1))
clashes = []
for line in lines[2:]:
    k = line.split(':', 1)[0].strip()
    other = known.get(murmur3(k))
    if other and other != k:
        clashes.append((k, other))
for k, other in clashes:
    print(f'CLASH: {k} has the same hash as {other}; change SUFFIX here and in the cast window', file=sys.stderr)

open(OUT, 'wb').write(b'\xef\xbb\xbf' + ('\n'.join(lines) + '\n').encode('utf-8'))
print(f'{len(names)} spells, {len(names) * SLOTS} entries written to {OUT}')
for key, n in too_long:
    print(f'WARNING: {key} has {n} prefixes; only the first {SLOTS} were kept', file=sys.stderr)
